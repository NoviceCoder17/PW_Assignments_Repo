const {test, expect} = require('@playwright/test')

test('Event hub locators and assertions', async({page})=>{
    await page.goto("/login")
    await page.getByPlaceholder('you@email.com').fill('prema.pisces@gmail.com')
    await page.locator("#password").fill('Test@123$')
    await page.locator('#login-btn').click()
    await page.locator("#nav-events").click()
    await expect(page.getByText('Upcoming Events')).toBeVisible()
    await page.getByPlaceholder('Search events, venues…').fill('World')
    await page.locator('.flex-col select').first().selectOption('Conference')
    await page.locator('.flex-col select').last().selectOption('Hyderabad')
    await expect(page.locator('#event-card')).toHaveCount(1)
    const eventName = await page.locator('#event-card h3').textContent()
    expect(eventName).toBe('World Tech Summit')
    const eventPrice = await page.locator('#event-card p').textContent()
    expect(eventPrice).toContain('$')
    const seatCount = await page.getByText('seats left').textContent()
    expect(parseInt(seatCount.trim())).toBeGreaterThan(0)
    const card = page.locator('#event-card').filter({ hasText: 'World Tech Summit' })
    await card.getByRole("link",{name: 'Book Now'}).click()
    await expect(page).toHaveURL(/events/)
    await expect(page.getByRole('heading', { level: 1 })).toHaveText(eventName)
    await expect(page.locator('span.text-2xl')).toHaveText(eventPrice)
    await page.goBack()
    await page.getByRole("button",{name:'Clear filters'}).click()
    const cards = page.locator('.grid-cols-1').first().locator('#event-card')
    await cards.nth(2).waitFor()
    expect(await cards.count()).toBeGreaterThanOrEqual(3)
    const firstTitle = await cards.first().locator('h3').textContent()
    const secondTitle = await cards.nth(1).locator('h3').textContent()
    const lastTitle = await cards.last().locator('h3').textContent()
    expect(firstTitle).not.toBe('')
    expect(secondTitle).not.toBe('')
    expect(lastTitle).not.toBe('')
    expect(firstTitle).not.toBe(lastTitle)
})